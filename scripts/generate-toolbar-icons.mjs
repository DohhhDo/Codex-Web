import { readFile, writeFile } from 'node:fs/promises';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';

// CodeMirror's DOM toolbar cannot consume React components directly. Generate
// its static SVGs from the same MIT-licensed Phosphor package as the React UI.
const icons = {};
for (const name of ['Eye', 'EyeSlash', 'ArrowsInSimple', 'ArrowsOutSimple', 'CaretUp', 'CaretDown', 'ArrowSquareOut']) {
  const module = await import(`@phosphor-icons/react/dist/csr/${name}`);
  icons[name] = renderToStaticMarkup(createElement(module[`${name}Icon`], {
    size: 16, weight: 'regular', 'aria-hidden': true, focusable: false,
  }));
}
const file = new URL('../src/modules/code-editor/utils/editorToolbarPanel.ts', import.meta.url);
const source = await readFile(file, 'utf8');
const block = `// BEGIN PHOSPHOR TOOLBAR ICONS
// Generated by scripts/generate-toolbar-icons.mjs. Phosphor Icons (MIT).
const TOOLBAR_ICONS = ${JSON.stringify(icons, null, 2)} as const;
// END PHOSPHOR TOOLBAR ICONS`;
await writeFile(file, source.replace(/\/\/ BEGIN PHOSPHOR TOOLBAR ICONS[\s\S]*?\/\/ END PHOSPHOR TOOLBAR ICONS/, block));
console.log('Generated Phosphor icons for the CodeMirror toolbar.');
